#!/usr/bin/env python3
"""Generate src/activity/mi_fitness_report_tables.c from the extracted Mi Fitness data.

Inputs (third_party/mi-fitness-tables/):
  sport_reports.json    report field tables (+ validity lengths, which mi_fitness_validity.c already has)
  sport_types.json      FitnessSportType id -> English name
  schema_field_ids.json Mi Fitness schema field name -> report field id (SportReportBaseParser.ReportType)
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
T = ROOT / "third_party" / "mi-fitness-tables"
reports = json.loads((T / "sport_reports.json").read_text())
types = json.loads((T / "sport_types.json").read_text())
names = json.loads((T / "schema_field_ids.json").read_text())

out = ["/* Generated by scripts/gen_mi_fitness_reports.py — do not edit. */",
       '#include "miwear/activity/mi_fitness_report_tables.h"', "", "#include <stdlib.h>", "#include <string.h>", ""]

def cname(parser):
    return "f_" + parser.replace("ReportParser", "").lower()

for r in reports["reports"]:
    out.append(f"static const MiFitnessOneDimenField {cname(r['parser'])}[] = {{")
    for t, bc, sv, fl, uns, cnt, dep in r["fields"]:
        if dep:
            vals = dep[1][:4]
            dv = ", ".join(str(v) for v in vals) + ", 0" * (4 - len(vals))
            out.append(f"    {{{t}, {bc}, {sv}, {fl}, {uns}, {cnt}, 1, 0, {dep[0]}, {len(vals)}, {{{dv}}}}},")
        else:
            out.append(f"    {{{t}, {bc}, {sv}, {fl}, {uns}, {cnt}, 0, 0, 0, 0, {{0, 0, 0, 0}}}},")
    out.append("};")
    out.append("")

# Health / GPS tables (public names used by mi_fitness_health.c and workout_record.c).
OTHER_NAMES = {
    "SportGpsParser.dataTypeArray": "mi_fitness_sport_gps_fields",
    "WeightRecordParser.recordDataTypeArray": "mi_fitness_weight_record_fields",
    "AbnormalRecordParser.dataTypeArray": "mi_fitness_abnormal_record_fields",
    "EcgMeasureParser.reportDataTypeArray": "mi_fitness_ecg_measure_fields",
    "EcgMeasureParser.recordDataTypeArray": "mi_fitness_ecg_record_fields",
    "TemperatureMeasureParser.recordDataTypeArray": "mi_fitness_temperature_measure_fields",
}
for key, fields in reports["others"].items():
    n = OTHER_NAMES[key]
    out.append(f"/* {key} */")
    out.append(f"const MiFitnessOneDimenField {n}[] = {{")
    for t, bc, sv, fl, uns, cnt, dep in fields:
        assert dep is None
        out.append(f"    {{{t}, {bc}, {sv}, {fl}, {uns}, {cnt}, 0, 0, 0, 0, {{0, 0, 0, 0}}}},")
    out.append("};")
    out.append(f"const size_t {n[:-len('_fields')]}_field_count = {len(fields)};")
    out.append("")

out.append("const MiFitnessOneDimenField *mi_fitness_report_fields(int sport_type, size_t *count, const char **parser) {")
out.append("    switch (sport_type) {")
for r in reports["reports"]:
    for s in r["sports"]:
        out.append(f"        case {s}:")
    n = cname(r["parser"])
    out.append(f"            if (count) *count = sizeof({n}) / sizeof({n}[0]);")
    out.append(f'            if (parser) *parser = "{r["parser"]}";')
    out.append(f"            return {n};")
out.append("        default:")
out.append("            if (count) *count = 0;")
out.append("            if (parser) *parser = NULL;")
out.append("            return NULL;")
out.append("    }")
out.append("}")
out.append("")

out.append("typedef struct {\n    const char *name;\n    int id;\n} SchemaFieldId;")
out.append("")
out.append("static const SchemaFieldId schema_ids[] = {")
for k in sorted(names):
    out.append(f'    {{"{k}", {names[k]}}},')
out.append("};")
out.append("")
out.append("static int cmp_name(const void *key, const void *elem) {")
out.append("    return strcmp((const char *)key, ((const SchemaFieldId *)elem)->name);")
out.append("}")
out.append("")
out.append("int mi_fitness_schema_field_id(const char *name) {")
out.append("    if (name == NULL) return MI_FITNESS_FIELD_UNKNOWN;")
out.append("    const SchemaFieldId *hit = bsearch(name, schema_ids, sizeof(schema_ids) / sizeof(schema_ids[0]), sizeof(schema_ids[0]), cmp_name);")
out.append("    return hit != NULL ? hit->id : MI_FITNESS_FIELD_UNKNOWN;")
out.append("}")
out.append("")

out.append("const char *mi_fitness_sport_type_name(int sport_type) {")
out.append("    switch (sport_type) {")
for k in sorted(types, key=int):
    out.append(f'        case {k}: return "{types[k]}";')
out.append("        default: return NULL;")
out.append("    }")
out.append("}")

(ROOT / "src" / "activity" / "mi_fitness_report_tables.c").write_text("\n".join(out) + "\n")
print("wrote", ROOT / "src" / "activity" / "mi_fitness_report_tables.c")
